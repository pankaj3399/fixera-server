const roundMoney = (value: number): number => Math.round((value + Number.EPSILON) * 100) / 100;

const finite = (value: unknown): number | undefined => {
  const parsed = Number(value);
  return value !== null && value !== '' && Number.isFinite(parsed) ? parsed : undefined;
};

const toIso = (value: unknown): string | null => {
  if (!value) return null;
  const date = value instanceof Date ? value : new Date(value as any);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
};

const toDate = (value: unknown): Date | null => {
  if (!value) return null;
  const date = value instanceof Date ? value : new Date(value as any);
  return Number.isNaN(date.getTime()) ? null : date;
};

/**
 * Client bug list #23a (hour mode): schedule-family timeline events must
 * carry the start/end time, not just the date. The status-history note that
 * produces the event records no schedule, so the current booking schedule is
 * attached (the 'Schedule selected' note is written once when the schedule
 * is set; reschedules create their own events with full snapshots).
 */
const currentScheduleFacts = (booking: any): Record<string, string | null> | null => {
  const startDate = toIso(booking?.scheduledStartDate);
  const executionEndDate = toIso(booking?.scheduledExecutionEndDate);
  const startTime =
    typeof booking?.scheduledStartTime === 'string' ? booking.scheduledStartTime : null;
  const endTime =
    typeof booking?.scheduledEndTime === 'string' ? booking.scheduledEndTime : null;
  if (!startDate && !executionEndDate && startTime == null && endTime == null) {
    return null;
  }
  return {
    startDate,
    startTime,
    endTime,
    executionEndDate,
    timeZone:
      typeof booking?.scheduleTimeZone === 'string' ? booking.scheduleTimeZone : null,
  };
};

const SCHEDULE_FACT_TYPES = new Set([
  'schedule_selected',
  'execution_extended',
  'planning_updated',
]);

const reference = (value: any): string => {
  const id = referenceId(value);
  return id || String(value ?? '');
};

export { opaqueRefundReference };

type PushEvent = Omit<ActivityItem, 'descriptionLocale' | 'descriptionSource' | 'titleKey'> & {
  titleKey?: string;
  /** Explicit provenance when the text is generated by the backend, not typed by the actor. */
  descriptionOrigin?: 'user' | 'system' | 'admin';
};

const humanizeType = (type: string): string =>
  type
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');

const markStatusCovered = (
  covered: Array<{ status: string; timestamp: number }>,
  status: string | null | undefined,
  value: unknown,
) => {
  const date = toDate(value);
  if (!status || !date) return;
  covered.push({ status, timestamp: date.getTime() });
};

const isStatusCovered = (
  covered: Array<{ status: string; timestamp: number }>,
  status: string,
  value: unknown,
): boolean => {
  const date = toDate(value);
  if (!date) return false;
  return covered.some(
    (entry) => entry.status === status && Math.abs(entry.timestamp - date.getTime()) <= 5000,
  );
};

const noteType = (note: string, status: string, actor: ActorDto | null, hasActor: boolean): string => {
  const value = note.toLowerCase();
  if (value.includes('force-set by admin')) return 'admin_status_changed';
  if (value.startsWith('schedule selected')) return 'schedule_selected';
  if (value.startsWith('professional accepted the rfq')) return 'rfq_accepted';
  if (value.startsWith('professional rejected the rfq')) return 'rfq_rejected';
  if (value.startsWith('customer accepted quotation')) return 'quotation_accepted';
  if (value.startsWith('customer accepted the quote')) return 'quotation_accepted';
  // RFQ review can be resolved by accepting the standard VAT rate, which
  // restores the fixed-price checkout and writes a real `quote_accepted`
  // status entry. It is a customer acceptance, not a generic status change.
  if (value.startsWith('customer chose standard vat rate')) return 'quotation_accepted';
  if (value.startsWith('customer rejected quotation')) return 'quotation_rejected';
  if (value.startsWith('customer rejected the quote')) return 'quotation_rejected';
  if (value.startsWith('payment intent cancel') || value.startsWith('payment intent cancelled')) {
    return 'payment_canceled';
  }
  if (value.startsWith('quotation submitted')) return 'quotation_submitted';
  if (value.startsWith('quotation updated')) return 'quotation_revised';
  if (value.startsWith('customer accepted the rescheduling')) return 'reschedule_accepted';
  if (value.startsWith('customer declined rescheduling')) {
    return value.includes('refund') ? 'reschedule_refunded' : 'reschedule_declined';
  }
  if (value.startsWith('execution extended')) return 'execution_extended';
  if (value.startsWith('planning updated')) return 'planning_updated';
  if (value.startsWith('customer confirmed completion')) return 'completion_confirmed';
  if (value.startsWith('customer disputed')) return 'dispute_opened';
  if (value.startsWith('booking created')) return 'booking_created';
  if (status === 'completed') {
    if (actor?.role === 'system' || /auto[- ]?accept|finali[sz]ed/i.test(value)) {
      return 'completion_auto_accepted';
    }
    return hasActor ? 'completion_confirmed' : 'completion_auto_accepted';
  }
  if (status === 'professional_completed') return 'completion_requested';
  if (status === 'in_progress') return 'work_started';
  return 'status_changed';
};

const categoryForType = (type: string): ActivityItem['category'] => {
  if (type.startsWith('rfq_')) return 'rfq';
  if (type.startsWith('quotation_')) return 'quotation';
  if (type.startsWith('payment_')) return 'payment';
  if (type.startsWith('refund_')) return 'refund';
  if (type.startsWith('reschedule_') || type === 'schedule_selected' || type === 'execution_extended' || type === 'planning_updated') {
    return 'schedule';
  }
  if (type.startsWith('completion_') || type.startsWith('milestone_') || type === 'work_started') return 'completion';
  if (type.startsWith('extra_costs_')) return 'extra_cost';
  if (type.startsWith('cancellation_')) return 'cancellation';
  if (type.startsWith('warranty_')) return 'warranty';
  if (type.startsWith('dispute_')) return 'dispute';
  if (type.startsWith('review_')) return 'review';
  if (type === 'post_booking_answers_submitted') return 'lifecycle';
  if (type === 'admin_status_changed' || type === 'status_changed') return 'system';
  return 'lifecycle';
};

const sourceForType = (type: string): ActivityItem['source'] => {
  if (type.startsWith('quotation_') || type.startsWith('rfq_')) return 'quotation';
  if (type.startsWith('payment_')) return 'payment';
  if (type.startsWith('refund_')) return 'refund';
  if (type.startsWith('reschedule_') || type === 'schedule_selected' || type === 'execution_extended' || type === 'planning_updated') return 'reschedule';
  if (type.startsWith('cancellation_')) return 'cancellation';
  if (type.startsWith('warranty_')) return 'warranty';
  if (type.startsWith('dispute_')) return 'dispute';
  if (type.startsWith('review_')) return 'review';
  if (type === 'post_booking_answers_submitted') return 'post_booking';
  if (type === 'admin_status_changed') return 'admin';
  return 'status_history';
};

interface TimelineContext {
  booking: any;
  payments: any[];
  cancellations: any[];
  warrantyClaims: any[];
  actors: ActorMap;
  viewerRole: DetailsViewerRole;
  customerId: string | null;
  professionalId: string | null;
  adminAccess?: {
    bookings?: boolean;
    disputes: boolean;
    warranty: boolean;
    cancellations: boolean;
    payments: boolean;
  };
}

export const buildBookingActivity = async (context: TimelineContext): Promise<BookingActivityDto> => {
  const {
    booking,
    payments,
    cancellations,
    warrantyClaims,
    actors,
    viewerRole,
    customerId,
    professionalId,
    adminAccess,
  } = context;

  const events: ActivityItem[] = [];
  const seenIds = new Set<string>();
  const coveredStatus: Array<{ status: string; timestamp: number }> = [];
  let undatedEvents = 0;
  const qualityNotes = new Set<string>();

  const pushEvent = (event: PushEvent) => {
    if (!event.occurredAt || seenIds.has(event.id)) return;
    const type = event.type;
    seenIds.add(event.id);
    const { descriptionOrigin, ...activityEvent } = event;
    const descriptionSource = activityEvent.description
      ? (descriptionOrigin
        || (activityEvent.actor?.role === 'admin'
          ? 'admin'
          : activityEvent.actor?.role === 'system'
            ? 'system'
            : activityEvent.actor
              ? 'user'
              : 'system'))
      : 'not_recorded';
    events.push({
      ...activityEvent,
      titleKey: activityEvent.titleKey || `activity.${type}`,
      titleEn: viewerRole === 'admin' ? humanizeType(type) : undefined,
      descriptionSource,
      descriptionLocale: activityEvent.description
        ? (descriptionSource === 'system' ? 'en' : 'unknown')
        : null,
    } as ActivityItem);
  };

  const evidenceAttachments = async (
    urls: unknown,
    owners: Array<string | null>,
    source: AttachmentDto['source'],
  ): Promise<AttachmentDto[]> => {
    if (!Array.isArray(urls)) return [];
    const attachments: AttachmentDto[] = [];
    for (const url of urls) {
      const result = await presignOwnedUrl(url, owners, [
        'dispute-attachments',
        'rfq-attachments',
        'completion-attachments',
        'warranty-claims',
      ]);
      if (!result.signed && result.unavailableReason === 'not_owned') {
        qualityNotes.add('LEGACY_ATTACHMENT_OWNER_NOT_RECORDED');
      }
      attachments.push({
        url: result.url,
        fileName: (() => {
          if (typeof url !== 'string') return null;
          try {
            return decodeURIComponent(new URL(url).pathname.split('/').filter(Boolean).pop() || '') || null;
          } catch {
            return null;
          }
        })(),
        source,
        signed: result.signed,
        ...(result.unavailableReason ? { unavailableReason: result.unavailableReason } : {}),
      });
    }
    return attachments;
  };

  const sharedAttachments = async (
    urls: unknown,
    source: AttachmentDto['source'],
  ): Promise<AttachmentDto[]> => {
    if (!Array.isArray(urls)) return [];
    const attachments: AttachmentDto[] = [];
    for (const url of urls) {
      const result = await presignOwnedUrl(url, [professionalId, customerId], [
        'completion-attachments',
        'dispute-attachments',
        'rfq-attachments',
      ]);
      attachments.push({
        url: result.url,
        fileName: (() => {
          if (typeof url !== 'string') return null;
          try {
            return decodeURIComponent(new URL(url).pathname.split('/').filter(Boolean).pop() || '') || null;
          } catch {
            return null;
          }
        })(),
        source,
        signed: result.signed,
        ...(result.unavailableReason ? { unavailableReason: result.unavailableReason } : {}),
      });
    }
    return attachments;
  };

  // ── RFQ submission ──────────────────────────────────────────────────────
  // The RFQ request is the booking itself for an RFQ-stage record. Its first
  // status entry is the authoritative creation boundary; newer records store
  // the customer as updatedBy. Legacy records without an actor keep that fact
  // explicit instead of inferring the current customer.
  const statusHistory = Array.isArray(booking.statusHistory) ? booking.statusHistory : [];
  const firstStatus = statusHistory[0] || null;
  const rfqSubmittedAt = firstStatus?.status === 'rfq'
    ? toIso(firstStatus.timestamp)
    : (!firstStatus && ['rfq', 'rfq_accepted'].includes(String(booking.status))
      ? toIso(booking.createdAt)
      : null);
  if (rfqSubmittedAt) {
    const submittedActor = actorForId(firstStatus?.updatedBy, actors, viewerRole, {
      roleHint: 'customer',
    });
    const actorRecorded = isActorRecorded(submittedActor);
    if (!actorRecorded) qualityNotes.add('RFQ_SUBMISSION_ACTOR_NOT_RECORDED');
    pushEvent({
      id: 'rfq:submitted',
      type: 'rfq_submitted',
      category: 'rfq',
      occurredAt: rfqSubmittedAt,
      actor: submittedActor,
      actorRecorded,
      description: null,
      statusFrom: null,
      statusTo: 'rfq',
      attachments: [],
      metadata: firstStatus ? { statusHistoryIndex: 0 } : { derivedFromCreatedAt: true },
      source: 'status_history',
      visibility: 'participants',
      legacyDerived: !actorRecorded || !firstStatus,
    });
    markStatusCovered(coveredStatus, 'rfq', firstStatus?.timestamp || booking.createdAt);
  }

  // ── RFQ response ────────────────────────────────────────────────────────
  if (booking.rfqResponse?.respondedAt && booking.rfqResponse.action) {
    const accepted = booking.rfqResponse.action === 'accepted';
    const type = accepted ? 'rfq_accepted' : 'rfq_rejected';
    const recordedActor = actorForId(booking.rfqResponse.respondedBy, actors, viewerRole, {
      roleHint: 'professional',
    });
    const actor = recordedActor || inferredActor('professional');
    pushEvent({
      id: 'rfq:response',
      type,
      category: 'rfq',
      occurredAt: toIso(booking.rfqResponse.respondedAt)!,
      actor,
      actorRecorded: Boolean(booking.rfqResponse.respondedBy) || isActorRecorded(actor),
      description: booking.rfqResponse.rejectionReason || null,
      statusFrom: 'rfq',
      statusTo: accepted ? 'rfq_accepted' : 'cancelled',
      attachments: [],
      metadata: {},
      source: 'quotation',
      visibility: 'participants',
      legacyDerived: !recordedActor,
    });
    markStatusCovered(coveredStatus, accepted ? 'rfq_accepted' : 'cancelled', booking.rfqResponse.respondedAt);
  }

  // ── Quotation versions + legacy quote ───────────────────────────────────
  const versions = Array.isArray(booking.quoteVersions) ? booking.quoteVersions : [];
  for (const version of versions) {
    const createdAt = toDate(version.createdAt);
    if (!createdAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_QUOTE_VERSION');
      continue;
    }
    let actor = actorForId(version.createdBy, actors, viewerRole, { roleHint: 'professional' });
    let legacyDerived = false;
    if (!actor) {
      const matchingStatus = [...(booking.statusHistory || [])].reverse().find(
        (entry: any) =>
          entry?.status === 'quoted'
          && entry?.updatedBy
          && entry?.timestamp
          && Math.abs(new Date(entry.timestamp).getTime() - createdAt.getTime()) <= 5000,
      );
      if (matchingStatus?.updatedBy) {
        actor = actorForId(matchingStatus.updatedBy, actors, viewerRole, { roleHint: 'professional' });
      }
    }
    if (!actor) {
      actor = inferredActor('professional');
      legacyDerived = true;
      qualityNotes.add('QUOTE_ACTOR_NOT_RECORDED');
    }
    const isRevision = Number(version.version) > 1;
    const versionAmount = finite(version.totalAmount);
    const versionCurrency = typeof version.currency === 'string' && version.currency
      ? version.currency
      : null;
    pushEvent({
      id: `quote:${version.version}`,
      type: isRevision ? 'quotation_revised' : 'quotation_submitted',
      category: 'quotation',
      occurredAt: createdAt.toISOString(),
      actor,
      actorRecorded: Boolean(version.createdBy) || isActorRecorded(actor),
      description: version.changeNote || null,
      descriptionOrigin: 'user',
      statusFrom: isRevision ? 'quoted' : (booking.status === 'draft_quote' ? 'draft_quote' : 'rfq_accepted'),
      statusTo: 'quoted',
      ...(versionAmount != null
        ? {
            amounts: {
              amount: versionAmount,
              totalAmount: versionAmount,
              ...(versionCurrency ? { currency: versionCurrency } : {}),
            },
            ...(versionCurrency
              ? {
                  amountLines: [
                    { kind: 'professional' as const, amount: versionAmount, currency: versionCurrency, recorded: true as const },
                  ],
                }
              : {}),
          }
        : {}),
      attachments: [],
      metadata: {
        quotationNumber: version.quotationNumber,
        version: version.version,
      },
      source: 'quotation',
      visibility: 'participants',
      legacyDerived,
      noteCodes: legacyDerived ? ['QUOTE_ACTOR_NOT_RECORDED'] : undefined,
    });
    markStatusCovered(coveredStatus, 'quoted', version.createdAt);
  }

  if (booking.quote?.submittedAt && versions.length === 0) {
    const actor = actorForId(booking.quote.submittedBy, actors, viewerRole, { roleHint: 'professional' });
    const amount = finite(booking.quote.amount);
    pushEvent({
      id: 'quote:legacy',
      type: 'quotation_submitted',
      category: 'quotation',
      occurredAt: toIso(booking.quote.submittedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.quote.description || null,
      descriptionOrigin: 'user',
      statusFrom: null,
      statusTo: booking.status === 'quoted' ? 'quoted' : null,
      amounts: amount != null
        ? {
            amount,
            totalAmount: amount,
            ...(typeof booking.quote.currency === 'string' && booking.quote.currency
              ? { currency: booking.quote.currency }
              : {}),
          }
        : undefined,
      attachments: [],
      metadata: { legacyQuote: true },
      source: 'quotation',
      visibility: 'participants',
      legacyDerived: !isActorRecorded(actor),
      noteCodes: ['LEGACY_SIMPLE_QUOTE'],
    });
    markStatusCovered(coveredStatus, 'quoted', booking.quote.submittedAt);
  }

  const acceptedVersionNumber = finite(booking.acceptedQuoteVersion);
  const acceptedVersion = versions.find((version: any) => Number(version.version) === acceptedVersionNumber)
    || versions.find((version: any) => Number(version.version) === finite(booking.currentQuoteVersion));

  // ── Payment records ─────────────────────────────────────────────────────
  const resolvedPaymentRows = resolvePaymentRows(booking, payments);
  const paymentRows = resolvedPaymentRows.map((row) => row.payment);
  const paymentCanceledStatusEntry = (
    timestamp: unknown,
  ): { entry: any; index: number } | null => {
    const value = toDate(timestamp);
    if (!value) return null;
    const history = Array.isArray(booking.statusHistory) ? booking.statusHistory : [];
    for (const [index, entry] of history.entries()) {
      if (String(entry?.status) !== 'cancelled') continue;
      if (!/^payment intent cancel(?:l)?ed/i.test(String(entry?.note || '').trim())) continue;
      const entryTime = toDate(entry?.timestamp);
      if (entryTime && Math.abs(entryTime.getTime() - value.getTime()) <= 5000) {
        return { entry, index };
      }
    }
    return null;
  };
  for (const [index, payment] of paymentRows.entries()) {
    const paymentId = String(payment._id || booking._id);
    const paymentCurrency = typeof payment.currency === 'string' && payment.currency
      ? payment.currency
      : typeof booking.quote?.currency === 'string' && booking.quote.currency
        ? booking.quote.currency
        : null;
    const milestoneIndex = finite(payment.milestoneIndex);
    const baseMetadata: Record<string, any> = {
      paymentId,
      ...(milestoneIndex != null ? { milestoneIndex } : {}),
      ...(payment.milestoneTitle ? { milestoneTitle: payment.milestoneTitle } : {}),
    };
    const hasPaymentAmount = finite(payment.netAmount) != null
      || finite(payment.vatAmount) != null
      || finite(payment.totalWithVat) != null;
    const amounts = hasPaymentAmount
      ? {
          ...(finite(payment.netAmount) != null ? { netAmount: finite(payment.netAmount) } : {}),
          ...(finite(payment.vatAmount) != null ? { vatAmount: finite(payment.vatAmount) } : {}),
          ...(finite(payment.totalWithVat) != null
            ? { totalAmount: finite(payment.totalWithVat), amount: finite(payment.totalWithVat) }
            : {}),
          ...(paymentCurrency ? { currency: paymentCurrency } : {}),
        }
      : undefined;
    const paymentEvents: Array<[string, unknown]> = [
      ['payment_authorized', payment.authorizedAt],
      ['payment_captured', payment.capturedAt || payment.paidAt],
      ['payment_released', payment.transferredAt],
      ['payment_failed', payment.failedAt],
      ['payment_canceled', payment.canceledAt],
      ['payment_disputed', payment.disputeOpenedAt],
    ];
    for (const [type, timestamp] of paymentEvents) {
      const iso = toIso(timestamp);
      if (!iso) continue;
      // The payment_intent.canceled webhook writes one status-history entry for
      // the same fact. Use that recorded entry's actor/description on the one
      // payment event, then suppress the generic status-loop duplicate.
      const canceledEntry = type === 'payment_canceled'
        ? paymentCanceledStatusEntry(timestamp)
        : null;
      const canceledActor = canceledEntry
        ? actorForId(canceledEntry.entry?.updatedBy, actors, viewerRole)
        : null;
      pushEvent({
        id: `payment:${paymentId}:${type}:${iso}`,
        type,
        category: 'payment',
        occurredAt: iso,
        actor: canceledActor || systemActor('provider_webhook'),
        actorRecorded: canceledActor ? isActorRecorded(canceledActor) : true,
        description: canceledEntry?.entry?.note || null,
        ...(canceledEntry ? { descriptionOrigin: 'system' as const } : {}),
        statusFrom: null,
        statusTo: type === 'payment_authorized'
          ? 'booked'
          : canceledEntry
            ? 'cancelled'
            : null,
        amounts,
        ...(type === 'payment_released' && paymentCurrency && (
          finite(payment.transferAmount) != null || finite(payment.professionalPayout) != null
        )
          ? {
              amountLines: [{
                kind: 'payout' as const,
                amount: finite(payment.transferAmount) ?? finite(payment.professionalPayout)!,
                currency: paymentCurrency,
                recorded: true as const,
              }],
            }
          : {}),
        attachments: [],
        metadata: {
          ...baseMetadata,
          paymentIndex: index,
          ...(canceledEntry ? { statusHistoryIndex: canceledEntry.index } : {}),
        },
        source: 'payment',
        visibility: 'participants',
      });
      if (type === 'payment_authorized' || type === 'payment_captured') {
        markStatusCovered(coveredStatus, 'booked', timestamp);
      }
      if (canceledEntry) {
        markStatusCovered(coveredStatus, 'cancelled', timestamp);
      }
    }
  }

  // ── Refund ledger (Payment rows + booking aggregate + cancellation) ────
  const refundFacts = resolveRefundFacts({
    booking,
    paymentRows: resolvedPaymentRows,
    quoteCurrency: typeof booking.quote?.currency === 'string' ? booking.quote.currency : null,
  });
  for (const fact of refundFacts) {
    if (!fact.refundedAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_REFUND');
      continue;
    }
    if (!fact.vatSplitRecorded) qualityNotes.add('REFUND_VAT_SPLIT_NOT_RECORDED');
    const refundActor = actorForId(fact.actorId, actors, viewerRole);
    const refundRef = refundFactReference(fact);
    pushEvent({
      id: `refund:${fact.paymentId || 'booking'}:${refundRef}`,
      type: 'refund_issued',
      category: 'refund',
      occurredAt: fact.refundedAt,
      actor: refundActor || systemActor('provider_webhook'),
      actorRecorded: refundActor ? isActorRecorded(refundActor) : true,
      description: fact.justification,
      statusFrom: null,
      statusTo: null,
      amounts: {
        amount: fact.amount,
        ...(fact.currency ? { currency: fact.currency } : {}),
        ...(fact.netAmount != null ? { netAmount: fact.netAmount } : {}),
        ...(fact.vatAmount != null ? { vatAmount: fact.vatAmount } : {}),
      },
      attachments: [],
      metadata: {
        ...(fact.paymentId ? { paymentId: fact.paymentId } : {}),
        ...(fact.paymentIndex != null ? { paymentIndex: fact.paymentIndex } : {}),
        refundRef,
        refundSource: fact.source,
        refundKind: fact.kind,
        ...(fact.providerRefundId && viewerRole === 'admin' && adminAccess?.payments
          ? { providerRefundId: fact.providerRefundId }
          : {}),
        ...(fact.internalNotes && viewerRole === 'admin' && adminAccess?.payments
          ? { internalNotes: fact.internalNotes }
          : {}),
        ...(fact.cancellationRequestId
          ? { cancellationRequestId: fact.cancellationRequestId }
          : {}),
      },
      source: 'refund',
      visibility: 'participants',
      noteCodes: fact.vatSplitRecorded ? undefined : ['REFUND_VAT_SPLIT_NOT_RECORDED'],
    });
    markStatusCovered(coveredStatus, 'refunded', fact.refundedAt);
  }

  // ── Milestones ──────────────────────────────────────────────────────────
  const milestones = Array.isArray(booking.milestonePayments) ? booking.milestonePayments : [];
  for (const [index, milestone] of milestones.entries()) {
    const currency = (typeof booking.payment?.currency === 'string' && booking.payment.currency)
      || (typeof booking.quote?.currency === 'string' && booking.quote.currency)
      || null;
    const baseMetadata = { milestoneIndex: index, milestoneTitle: milestone.title };
    if (toIso(milestone.startedAt)) {
      pushEvent({
        id: `milestone:${index}:started`,
        type: 'milestone_started',
        category: 'completion',
        occurredAt: toIso(milestone.startedAt)!,
        actor: inferredActor('professional'),
        actorRecorded: false,
        description: null,
        statusFrom: null,
        statusTo: null,
        amounts: finite(milestone.amount) != null
          ? { amount: milestone.amount, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: baseMetadata,
        source: 'status_history',
        visibility: 'participants',
        legacyDerived: true,
      });
    }
    if (toIso(milestone.completedAt)) {
      pushEvent({
        id: `milestone:${index}:completed`,
        type: 'milestone_completed',
        category: 'completion',
        occurredAt: toIso(milestone.completedAt)!,
        actor: inferredActor('professional'),
        actorRecorded: false,
        description: null,
        statusFrom: null,
        statusTo: null,
        amounts: finite(milestone.amount) != null
          ? { amount: milestone.amount, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: baseMetadata,
        source: 'status_history',
        visibility: 'participants',
        legacyDerived: true,
      });
    }
    if (toIso(milestone.paidAt)) {
      pushEvent({
        id: `milestone:${index}:paid`,
        type: 'milestone_paid',
        category: 'payment',
        occurredAt: toIso(milestone.paidAt)!,
        actor: systemActor('provider_webhook'),
        actorRecorded: true,
        description: null,
        statusFrom: null,
        statusTo: null,
        amounts: finite(milestone.amount) != null
          ? { amount: milestone.amount, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: baseMetadata,
        source: 'payment',
        visibility: 'participants',
      });
    }
  }

  // ── Completion attestation ──────────────────────────────────────────────
  if (booking.completionAttestation?.confirmedAt) {
    const actor = actorForId(booking.completionAttestation.confirmedBy, actors, viewerRole, {
      roleHint: 'professional',
    });
    pushEvent({
      id: 'completion:requested',
      type: 'completion_requested',
      category: 'completion',
      occurredAt: toIso(booking.completionAttestation.confirmedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.completionAttestation.notes || null,
      statusFrom: null,
      statusTo: 'professional_completed',
      attachments: await sharedAttachments(booking.completionAttestation.attachments, 'completion'),
      metadata: {},
      source: 'status_history',
      visibility: 'participants',
    });
    markStatusCovered(coveredStatus, 'professional_completed', booking.completionAttestation.confirmedAt);
  }

  // ── Extra costs ─────────────────────────────────────────────────────────
  const extraCosts = Array.isArray(booking.extraCosts) ? booking.extraCosts : [];
  if (extraCosts.length > 0) {
    const declaredAt = booking.completionAttestation?.confirmedAt || booking.professionalCompletedAt;
    const currency = (typeof booking.payment?.currency === 'string' && booking.payment.currency)
      || (typeof booking.quote?.currency === 'string' && booking.quote.currency)
      || null;
    if (!declaredAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_EXTRA_COSTS');
    } else {
      pushEvent({
        id: 'extra-costs:declared',
        type: 'extra_costs_declared',
        category: 'extra_cost',
        occurredAt: toIso(declaredAt)!,
        actor: actorForId(booking.completionAttestation?.confirmedBy, actors, viewerRole, {
          roleHint: 'professional',
        }),
        actorRecorded: Boolean(booking.completionAttestation?.confirmedBy),
        description: booking.completionAttestation?.notes || null,
        statusFrom: null,
        statusTo: 'professional_completed',
        amounts: finite(booking.extraCostTotal) != null
          ? { amount: booking.extraCostTotal, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: { items: extraCosts.map((item: any) => ({ name: item.name, type: item.type, amount: item.amount })) },
        source: 'status_history',
        visibility: 'participants',
      });
    }
    const extraCostPayment = booking.payment || {};
    if (toIso(extraCostPayment.extraCostPaidAt)) {
      pushEvent({
        id: 'extra-costs:paid',
        type: 'extra_costs_paid',
        category: 'extra_cost',
        occurredAt: toIso(extraCostPayment.extraCostPaidAt)!,
        actor: systemActor('provider_webhook'),
        actorRecorded: true,
        description: null,
        statusFrom: null,
        statusTo: null,
        amounts: finite(extraCostPayment.extraCostAmount) != null
          ? { amount: extraCostPayment.extraCostAmount, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: {},
        source: 'payment',
        visibility: 'participants',
      });
    }
    if (toIso(extraCostPayment.extraCostFailedAt)) {
      pushEvent({
        id: 'extra-costs:failed',
        type: 'extra_costs_payment_failed',
        category: 'extra_cost',
        occurredAt: toIso(extraCostPayment.extraCostFailedAt)!,
        actor: systemActor('provider_webhook'),
        actorRecorded: true,
        description: null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: {},
        source: 'payment',
        visibility: 'participants',
      });
    }
  }

  // ── Dispute ─────────────────────────────────────────────────────────────
  if (booking.dispute?.raisedAt) {
    const actor = actorForId(booking.dispute.raisedBy, actors, viewerRole, { roleHint: 'customer' });
    const isExtraCostDispute = booking.dispute.type === 'extra_costs';
    pushEvent({
      id: 'dispute:opened',
      type: isExtraCostDispute ? 'extra_costs_disputed' : 'dispute_opened',
      category: isExtraCostDispute ? 'extra_cost' : 'dispute',
      occurredAt: toIso(booking.dispute.raisedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.dispute.reason || null,
      statusFrom: null,
      statusTo: 'dispute',
      attachments: await evidenceAttachments(booking.dispute.attachments, [booking.dispute.raisedBy, customerId, professionalId], 'dispute'),
      metadata: { disputeType: booking.dispute.type },
      source: 'dispute',
      visibility: 'participants',
    });
    markStatusCovered(coveredStatus, 'dispute', booking.dispute.raisedAt);
  }
  if (booking.dispute?.resolvedAt) {
    const actor = actorForId(booking.dispute.resolvedBy, actors, viewerRole, { roleHint: 'admin' });
    pushEvent({
      id: 'dispute:resolved',
      type: 'dispute_resolved',
      category: 'dispute',
      occurredAt: toIso(booking.dispute.resolvedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: viewerRole === 'admin' ? booking.dispute.resolution || null : null,
      statusFrom: 'dispute',
      statusTo: null,
      amounts: finite(booking.dispute.adminAdjustedAmount) != null
        ? {
            amount: booking.dispute.adminAdjustedAmount,
            ...(booking.payment?.currency ? { currency: booking.payment.currency } : {}),
          }
        : undefined,
      attachments: [],
      metadata: { disputeType: booking.dispute.type },
      source: 'dispute',
      visibility: 'participants',
      ...(viewerRole !== 'admin' ? { noteCodes: ['DISPUTE_RESOLUTION_ADMIN_ONLY'] } : {}),
    });
  }

  // ── Reschedules ─────────────────────────────────────────────────────────
  const reschedules = [...(Array.isArray(booking.rescheduleHistory) ? booking.rescheduleHistory : [])];
  if (booking.rescheduleRequest?.requestedAt) {
    const alreadyRecorded = reschedules.some(
      (entry: any) =>
        toIso(entry.requestedAt) === toIso(booking.rescheduleRequest.requestedAt)
        && entry.reason === booking.rescheduleRequest.reason,
    );
    if (!alreadyRecorded) reschedules.push({ ...booking.rescheduleRequest, status: 'pending' });
  }
  for (const [index, reschedule] of reschedules.entries()) {
    const requestedAt = toIso(reschedule.requestedAt);
    if (!requestedAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_RESCHEDULE');
      continue;
    }
    const requestedBy = actorForId(reschedule.requestedBy, actors, viewerRole, { roleHint: 'customer' });
    const scheduleMetadata = {
      ...(reschedule.previousSchedule ? { previousSchedule: reschedule.previousSchedule } : {}),
      ...(reschedule.proposedSchedule ? { proposedSchedule: reschedule.proposedSchedule } : {}),
      ...(booking.scheduleTimeZone ? { timeZone: booking.scheduleTimeZone } : {}),
    };
    pushEvent({
      id: `reschedule:${index}:requested`,
      type: 'reschedule_requested',
      category: 'schedule',
      occurredAt: requestedAt,
      actor: requestedBy,
      actorRecorded: isActorRecorded(requestedBy),
      description: reschedule.reason || null,
      statusFrom: null,
      statusTo: 'rescheduling_requested',
      attachments: [],
      metadata: scheduleMetadata,
      source: 'reschedule',
      visibility: 'participants',
    });
    markStatusCovered(coveredStatus, 'rescheduling_requested', reschedule.requestedAt);
    const respondedAt = toIso(reschedule.respondedAt);
    if (respondedAt && reschedule.status !== 'pending') {
      const respondedBy = actorForId(reschedule.respondedBy, actors, viewerRole, { roleHint: 'customer' });
      // Client bug list #9c: a disputed request is terminal and distinct from
      // a plain decline — it moves the booking to dispute, not cancellation.
      const disputed = reschedule.status === 'disputed';
      const type = reschedule.status === 'accepted'
        ? 'reschedule_accepted'
        : disputed ? 'reschedule_disputed' : 'reschedule_declined';
      pushEvent({
        id: `reschedule:${index}:${reschedule.status}`,
        type,
        category: 'schedule',
        occurredAt: respondedAt,
        actor: respondedBy,
        actorRecorded: isActorRecorded(respondedBy),
        description: reschedule.responseNote || null,
        statusFrom: 'rescheduling_requested',
        statusTo: reschedule.status === 'accepted' ? 'booked' : disputed ? 'dispute' : 'cancelled',
        attachments: [],
        metadata: scheduleMetadata,
        source: 'reschedule',
        visibility: 'participants',
      });
      markStatusCovered(coveredStatus, reschedule.status === 'accepted' ? 'booked' : disputed ? 'dispute' : 'cancelled', reschedule.respondedAt);
    }
  }

  // ── Cancellation / refund negotiation ───────────────────────────────────
  for (const [index, request] of cancellations.entries()) {
    const createdAt = toIso(request.createdAt);
    if (!createdAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_CANCELLATION_REQUEST');
      continue;
    }
    const requestedBy = actorForId(request.requestedBy, actors, viewerRole, {
      roleHint: request.requestedRole === 'professional' ? 'professional' : 'customer',
    });
    const evidence = await evidenceAttachments(
      request.evidence,
      [request.requestedBy, customerId, professionalId],
      'cancellation',
    );
    const currency = booking.payment?.currency || booking.quote?.currency || null;
    pushEvent({
      id: `cancellation:${reference(request._id)}:requested`,
      type: 'cancellation_requested',
      category: 'cancellation',
      occurredAt: createdAt,
      actor: requestedBy,
      actorRecorded: isActorRecorded(requestedBy),
      description: request.reason || null,
      statusFrom: null,
      statusTo: null,
      attachments: evidence,
      metadata: {
        cancellationRequestId: reference(request._id),
        ...(request.reasonCategory ? { reasonCategory: request.reasonCategory } : {}),
      },
      source: 'cancellation',
      visibility: 'participants',
      noteCodes: evidence.some((attachment) => !attachment.signed) ? ['ATTACHMENT_UNAVAILABLE'] : undefined,
    });
    if (toIso(request.professionalRespondedAt)) {
      const responseRole: 'customer' | 'professional' =
        request.requestedRole === 'customer' ? 'professional' : 'customer';
      const respondedBy = request.professionalRespondedBy
        ? actorForId(request.professionalRespondedBy, actors, viewerRole, { roleHint: responseRole })
        : inferredActor(responseRole);
      const decision = request.professionalDecision;
      const type = decision === 'counter'
        ? 'cancellation_countered'
        : decision === 'approved'
          ? 'cancellation_approved'
          : 'cancellation_denied';
      pushEvent({
        id: `cancellation:${reference(request._id)}:professional-response`,
        type,
        category: 'cancellation',
        occurredAt: toIso(request.professionalRespondedAt)!,
        actor: respondedBy,
        actorRecorded: isActorRecorded(respondedBy),
        description: request.professionalNote || null,
        titleParams: { stage: 'professional_response' },
        statusFrom: null,
        statusTo: null,
        amounts: finite(request.counterOfferAmount) != null
          ? { amount: request.counterOfferAmount, ...(currency ? { currency } : {}) }
          : undefined,
        attachments: [],
        metadata: { cancellationRequestId: reference(request._id), stage: 'professional_response' },
        source: 'cancellation',
        visibility: 'participants',
      });
    }
    if (toIso(request.customerRespondedAt)) {
      const respondedBy = request.customerRespondedBy
        ? actorForId(request.customerRespondedBy, actors, viewerRole, { roleHint: 'customer' })
        : inferredActor('customer');
      const type = request.customerDecision === 'accepted' ? 'cancellation_approved' : 'cancellation_denied';
      pushEvent({
        id: `cancellation:${reference(request._id)}:customer-response`,
        type,
        category: 'cancellation',
        occurredAt: toIso(request.customerRespondedAt)!,
        actor: respondedBy,
        actorRecorded: isActorRecorded(respondedBy),
        description: null,
        titleParams: { stage: 'customer_response' },
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: { cancellationRequestId: reference(request._id), stage: 'customer_response' },
        source: 'cancellation',
        visibility: 'participants',
      });
    }
    if (toIso(request.escalatedAt)) {
      const actor = systemActor('system_job');
      pushEvent({
        id: `cancellation:${reference(request._id)}:escalated`,
        type: 'cancellation_escalated',
        category: 'cancellation',
        occurredAt: toIso(request.escalatedAt)!,
        actor,
        actorRecorded: true,
        description: request.escalationReason || null,
        statusFrom: null,
        statusTo: 'dispute',
        attachments: [],
        metadata: { cancellationRequestId: reference(request._id) },
        source: 'cancellation',
        visibility: 'participants',
      });
    }
    if (toIso(request.resolvedAt)) {
      const resolvedBy = actorForId(request.resolvedBy, actors, viewerRole, { roleHint: 'admin' });
      const denied = request.status === 'denied';
      pushEvent({
        id: `cancellation:${reference(request._id)}:resolved`,
        type: denied ? 'cancellation_denied' : 'cancellation_approved',
        category: 'cancellation',
        occurredAt: toIso(request.resolvedAt)!,
        actor: resolvedBy,
        actorRecorded: isActorRecorded(resolvedBy),
        description: request.denyReason || null,
        titleParams: { stage: 'final' },
        statusFrom: null,
        statusTo: denied ? null : 'cancelled',
        attachments: [],
        metadata: { cancellationRequestId: reference(request._id), stage: 'final' },
        source: 'cancellation',
        visibility: 'participants',
      });
      markStatusCovered(coveredStatus, denied ? null : 'cancelled', request.resolvedAt);
      markStatusCovered(coveredStatus, denied ? null : 'refunded', request.refundedAt);
    }
    if (toIso(request.refundedAt) && finite(request.refundAmount) != null && request.refundAmount > 0) {
      const recordedRefundMatch = refundFacts.some((fact) => {
        const refundTime = fact.refundedAt ? new Date(fact.refundedAt).getTime() : NaN;
        return Number.isFinite(refundTime)
          && Math.abs(refundTime - new Date(request.refundedAt).getTime()) <= 5 * 60 * 1000
          && Math.abs(fact.amount - Number(request.refundAmount)) < 0.01;
      });
      if (!recordedRefundMatch) {
        const cancellationRefundActor = actorForId(request.resolvedBy, actors, viewerRole, { roleHint: 'admin' });
        pushEvent({
          id: `cancellation:${reference(request._id)}:refund`,
          type: 'refund_issued',
          category: 'refund',
          occurredAt: toIso(request.refundedAt)!,
          actor: cancellationRefundActor || systemActor('provider_webhook'),
          actorRecorded: cancellationRefundActor ? isActorRecorded(cancellationRefundActor) : true,
          description: request.reason || null,
          statusFrom: null,
          statusTo: 'refunded',
          amounts: {
            amount: Number(request.refundAmount),
            ...(currency ? { currency } : {}),
          },
          attachments: [],
          metadata: { cancellationRequestId: reference(request._id) },
          source: 'refund',
          visibility: 'participants',
          noteCodes: ['REFUND_VAT_SPLIT_NOT_RECORDED'],
        });
        qualityNotes.add('REFUND_VAT_SPLIT_NOT_RECORDED');
      }
    }
  }

  // ── Warranty claims (summary only; detailed evidence stays on its route) ─
  for (const [index, claim] of warrantyClaims.entries()) {
    const base = {
      claimId: reference(claim._id),
      claimNumber: claim.claimNumber,
      reason: claim.reason,
    };
    const openedAt = toIso(claim.openedAt);
    if (!openedAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_WARRANTY_CLAIM');
      continue;
    }
    const customerActor = actorForId(claim.customer, actors, viewerRole, { roleHint: 'customer' });
    pushEvent({
      id: `warranty:${reference(claim._id)}:opened:${index}`,
      type: 'warranty_claim_opened',
      category: 'warranty',
      occurredAt: openedAt,
      actor: customerActor,
      actorRecorded: isActorRecorded(customerActor),
      description: null,
      statusFrom: null,
      statusTo: null,
      attachments: [],
      metadata: base,
      source: 'warranty',
      visibility: 'participants',
    });
    if (toIso(claim.proposal?.proposedAt)) {
      const actor = actorForId(claim.proposal?.proposedBy, actors, viewerRole, { roleHint: 'professional' });
      pushEvent({
        id: `warranty:${reference(claim._id)}:proposal`,
        type: 'warranty_proposal_sent',
        category: 'warranty',
        occurredAt: toIso(claim.proposal.proposedAt)!,
        actor,
        actorRecorded: isActorRecorded(actor),
        description: null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: { ...base, resolveByDate: toIso(claim.proposal?.resolveByDate) },
        source: 'warranty',
        visibility: 'participants',
      });
    }
    if (toIso(claim.proposal?.decidedAt)) {
      const actor = actorForId(claim.customer, actors, viewerRole, { roleHint: 'customer' });
      const accepted = claim.proposal?.customerDecision === 'accepted';
      pushEvent({
        id: `warranty:${reference(claim._id)}:decision`,
        type: accepted ? 'warranty_proposal_accepted' : 'warranty_proposal_declined',
        category: 'warranty',
        occurredAt: toIso(claim.proposal.decidedAt)!,
        actor,
        actorRecorded: isActorRecorded(actor),
        description: claim.proposal?.decisionNote || null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: base,
        source: 'warranty',
        visibility: 'participants',
      });
    }
    if (toIso(claim.escalation?.escalatedAt)) {
      const actor = claim.escalation?.autoEscalated
        ? systemActor('system_job')
        : actorForId(claim.escalation?.escalatedBy, actors, viewerRole, { roleHint: 'admin' });
      pushEvent({
        id: `warranty:${reference(claim._id)}:escalated`,
        type: 'warranty_escalated',
        category: 'warranty',
        occurredAt: toIso(claim.escalation.escalatedAt)!,
        actor,
        actorRecorded: isActorRecorded(actor) || Boolean(claim.escalation?.autoEscalated),
        description: claim.escalation?.reason || null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: base,
        source: 'warranty',
        visibility: 'participants',
      });
    }
    if (toIso(claim.resolution?.resolvedAt)) {
      const actor = actorForId(claim.resolution?.resolvedBy, actors, viewerRole, { roleHint: 'admin' });
      pushEvent({
        id: `warranty:${reference(claim._id)}:resolved`,
        type: 'warranty_resolved',
        category: 'warranty',
        occurredAt: toIso(claim.resolution.resolvedAt)!,
        actor,
        actorRecorded: isActorRecorded(actor),
        description: viewerRole === 'admin' ? claim.resolution?.summary || null : null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: base,
        source: 'warranty',
        visibility: 'participants',
        ...(viewerRole !== 'admin' ? { noteCodes: ['WARRANTY_RESOLUTION_DETAILS_ADMIN_ONLY'] } : {}),
      });
    }
    const lastClosedEntry = [...(claim.statusHistory || [])]
      .reverse()
      .find((entry: any) => entry.status === 'closed' && entry.timestamp);
    const closedAt = claim.resolution?.autoClosedAt || lastClosedEntry?.timestamp;
    if (toIso(closedAt)) {
      // The actual close writer records its actor on the `closed` status entry
      // (admin/customer close). Only an auto-close is a system job; a legacy
      // entry without updatedBy stays explicitly unrecorded.
      const autoClosed = Boolean(claim.resolution?.autoClosedAt);
      const closedActor = autoClosed
        ? systemActor('system_job')
        : actorForId(lastClosedEntry?.updatedBy, actors, viewerRole);
      pushEvent({
        id: `warranty:${reference(claim._id)}:closed`,
        type: 'warranty_closed',
        category: 'warranty',
        occurredAt: toIso(closedAt)!,
        actor: closedActor,
        actorRecorded: autoClosed || isActorRecorded(closedActor),
        description: viewerRole === 'admin' ? lastClosedEntry?.note || null : null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: base,
        source: 'warranty',
        visibility: 'participants',
        ...(!autoClosed && !isActorRecorded(closedActor)
          ? { legacyDerived: true, noteCodes: ['WARRANTY_CLOSE_ACTOR_NOT_RECORDED'] }
          : {}),
      });
    }
  }

  // ── Post-booking answers ────────────────────────────────────────────────
  if (booking.postBookingData?.length > 0) {
    const submittedAt = toIso(booking.postBookingSubmittedAt);
    if (!submittedAt) {
      undatedEvents += 1;
      qualityNotes.add('POST_BOOKING_TIMESTAMP_NOT_RECORDED');
    } else {
      const actor = actorForId(booking.postBookingSubmittedBy, actors, viewerRole, { roleHint: 'customer' });
      pushEvent({
        id: 'post-booking:submitted',
        type: 'post_booking_answers_submitted',
        category: 'lifecycle',
        occurredAt: submittedAt,
        actor,
        actorRecorded: isActorRecorded(actor),
        description: null,
        statusFrom: null,
        statusTo: null,
        attachments: [],
        metadata: { answerCount: booking.postBookingData.length },
        source: 'post_booking',
        visibility: 'participants',
      });
    }
  }

  // ── Reviews ─────────────────────────────────────────────────────────────
  if (toIso(booking.customerReview?.reviewedAt)) {
    const actor = actorForId(booking.customer, actors, viewerRole, { roleHint: 'customer' });
    pushEvent({
      id: 'review:customer',
      type: 'review_submitted',
      category: 'review',
      occurredAt: toIso(booking.customerReview.reviewedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.customerReview.comment || null,
      statusFrom: null,
      statusTo: null,
      attachments: [],
      metadata: {},
      source: 'review',
      visibility: 'participants',
    });
  }
  if (toIso(booking.customerReview?.reply?.repliedAt)) {
    const actor = actorForId(professionalId, actors, viewerRole, { roleHint: 'professional' });
    pushEvent({
      id: 'review:reply',
      type: 'review_replied',
      category: 'review',
      occurredAt: toIso(booking.customerReview.reply.repliedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.customerReview.reply.comment || null,
      statusFrom: null,
      statusTo: null,
      attachments: [],
      metadata: {},
      source: 'review',
      visibility: 'participants',
    });
  }
  if (toIso(booking.professionalReview?.reviewedAt)) {
    const actor = actorForId(professionalId, actors, viewerRole, { roleHint: 'professional' });
    pushEvent({
      id: 'review:professional',
      type: 'review_submitted',
      category: 'review',
      occurredAt: toIso(booking.professionalReview.reviewedAt)!,
      actor,
      actorRecorded: isActorRecorded(actor),
      description: booking.professionalReview.comment || null,
      statusFrom: null,
      statusTo: null,
      attachments: [],
      metadata: { by: 'professional' },
      source: 'review',
      visibility: 'participants',
    });
  }

  // ── Remaining status history ────────────────────────────────────────────
  const initialStatus = statusHistory[0] || (booking.createdAt ? {
    status: booking.status,
    timestamp: booking.createdAt,
    note: 'Booking created',
  } : null);
  for (const [index, entry] of statusHistory.entries()) {
    const occurredAt = toIso(entry.timestamp);
    if (!occurredAt) {
      undatedEvents += 1;
      qualityNotes.add('UNDATED_STATUS_HISTORY');
      continue;
    }
    if (isStatusCovered(coveredStatus, entry.status, entry.timestamp)) continue;
    const previous = index > 0 ? statusHistory[index - 1]?.status : null;
    const actor = actorForId(entry.updatedBy, actors, viewerRole, {
      roleHint: entry.updatedBy ? undefined : (index === 0 ? 'customer' : undefined),
    });
    const hasActor = isActorRecorded(actor);
    const type = noteType(entry.note || '', entry.status, actor, hasActor);
    if (type === 'quotation_submitted' || type === 'quotation_revised') {
      // A status entry without a version (legacy writer) may still be real.
      pushEvent({
        id: `status:${index}`,
        type,
        category: 'quotation',
        occurredAt,
        actor: actor || inferredActor('professional'),
        actorRecorded: hasActor,
        description: entry.note || null,
        descriptionOrigin: 'system',
        statusFrom: previous,
        statusTo: entry.status,
        attachments: [],
        metadata: { statusHistoryIndex: index },
        source: 'quotation',
        visibility: 'participants',
        legacyDerived: !hasActor,
      });
      continue;
    }
    if (type === 'booking_created' && index === 0 && !entry.updatedBy) {
      pushEvent({
        id: `status:${index}`,
        type,
        category: 'lifecycle',
        occurredAt,
        actor: actorForId(customerId, actors, viewerRole, { roleHint: 'customer', source: 'inferred_route' }),
        actorRecorded: false,
        description: entry.note || null,
        descriptionOrigin: 'system',
        statusFrom: null,
        statusTo: entry.status,
        attachments: [],
        metadata: { statusHistoryIndex: index },
        source: 'status_history',
        visibility: 'participants',
        legacyDerived: true,
      });
      continue;
    }
    const suppressAdminNote = viewerRole !== 'admin' && actor?.role === 'admin';
    const scheduleFacts = SCHEDULE_FACT_TYPES.has(type) ? currentScheduleFacts(booking) : null;
    pushEvent({
      id: `status:${index}`,
      type,
      category: categoryForType(type),
      occurredAt,
      actor,
      actorRecorded: hasActor,
      description: suppressAdminNote ? null : entry.note || null,
      descriptionOrigin: actor?.role === 'admin' ? 'admin' : 'system',
      statusFrom: previous,
      statusTo: entry.status,
      attachments: [],
      metadata: scheduleFacts
        ? { statusHistoryIndex: index, schedule: scheduleFacts }
        : { statusHistoryIndex: index },
      source: sourceForType(type),
      visibility: 'participants',
      legacyDerived: !hasActor,
      ...(suppressAdminNote ? { noteCodes: ['ADMIN_NOTE_ADMIN_ONLY'] } : {}),
    });
  }
  if (statusHistory.length === 0 && initialStatus && !rfqSubmittedAt) {
    const occurredAt = toIso(initialStatus.timestamp);
    if (occurredAt) {
      pushEvent({
        id: 'status:implicit-created',
        type: 'booking_created',
        category: 'lifecycle',
        occurredAt,
        actor: actorForId(customerId, actors, viewerRole, { roleHint: 'customer', source: 'inferred_route' }),
        actorRecorded: false,
        description: 'Booking created',
        descriptionOrigin: 'system',
        statusFrom: null,
        statusTo: initialStatus.status,
        attachments: [],
        metadata: {},
        source: 'status_history',
        visibility: 'participants',
        legacyDerived: true,
      });
    }
  }

  // Admin areas are separate permissions. A bookings.read admin without
  // cancellations/warranty/disputes access must not receive those records or
  // their timeline events through any booking alias.
  const permissionRestrictedCategories = new Set<ActivityItem['category']>();
  if (viewerRole === 'admin' && adminAccess) {
    if (!adminAccess.cancellations) permissionRestrictedCategories.add('cancellation');
    if (!adminAccess.warranty) permissionRestrictedCategories.add('warranty');
    if (!adminAccess.disputes) permissionRestrictedCategories.add('dispute');
  }
  const visibleEvents = permissionRestrictedCategories.size === 0
    ? events
    : events.filter((event) => {
        if (permissionRestrictedCategories.has(event.category)) return false;
        if (!adminAccess?.disputes && event.type === 'extra_costs_disputed') return false;
        return true;
      });

  visibleEvents.sort((a, b) => {
    const time = new Date(a.occurredAt).getTime() - new Date(b.occurredAt).getTime();
    return time !== 0 ? time : a.id.localeCompare(b.id);
  });

  const actorMissingEvents = visibleEvents.filter((event) => !event.actorRecorded).length;
  const legacyDerivedEvents = visibleEvents.filter((event) => event.legacyDerived).length;
  if (qualityNotes.has('QUOTE_ACTOR_NOT_RECORDED')) qualityNotes.add('LEGACY_QUOTE_ACTOR_MISSING');
  if (qualityNotes.has('LEGACY_ATTACHMENT_OWNER_NOT_RECORDED')) {
    qualityNotes.add('ATTACHMENT_UNAVAILABLE_FOR_LEGACY_RECORD');
  }

  return {
    generatedAt: new Date().toISOString(),
    complete: undatedEvents === 0,
    order: 'asc',
    items: visibleEvents,
    dataQuality: {
      undatedEvents,
      actorMissingEvents,
      legacyDerivedEvents,
      notes: [...qualityNotes],
    },
  };
};

export { roundMoney, finite, toIso, toDate };
